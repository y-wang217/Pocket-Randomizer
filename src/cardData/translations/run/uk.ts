/** Ukrainian plural: one, few (2-4, not 12-14), many. */
const plural = (n: number, one: string, few: string, many: string): string => {
  const ten = n % 10;
  const hundred = n % 100;
  if (ten === 1 && hundred !== 11) return one;
  if (ten >= 2 && ten <= 4 && (hundred < 12 || hundred > 14)) return few;
  return many;
};
const supplies = (n: number): string => plural(n, 'припас', 'припаси', 'припасів');

